\getenv catalog_password CATALOG_DB_PASSWORD
\getenv repositories_password REPOSITORIES_DB_PASSWORD
\getenv security_password SECURITY_DB_PASSWORD
\getenv workspace_password WORKSPACE_DB_PASSWORD
CREATE ROLE catalog LOGIN PASSWORD :'catalog_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE repositories LOGIN PASSWORD :'repositories_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE security LOGIN PASSWORD :'security_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE workspace LOGIN PASSWORD :'workspace_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE DATABASE catalog OWNER catalog;
CREATE DATABASE repositories OWNER repositories;
CREATE DATABASE security OWNER security;
CREATE DATABASE workspace OWNER workspace;
REVOKE ALL ON DATABASE catalog FROM PUBLIC;
REVOKE ALL ON DATABASE repositories FROM PUBLIC;
REVOKE ALL ON DATABASE security FROM PUBLIC;
REVOKE ALL ON DATABASE workspace FROM PUBLIC;
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;
